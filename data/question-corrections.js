/** Adds the textbook figures to the corrections of the questions that show them; the original picture stays documented. */
function withBookFigures(corrections) {
  const merged = { ...corrections };
  for (const [id, figure] of Object.entries(bookFigureImages)) {
    const existing = merged[id] ?? {};
    merged[id] = {
      ...existing,
      image: { src: `./assets/questions/${figure.file}`, alt: existing.image?.alt ?? figure.previousImage.alt },
      previousImage: "previousImage" in existing ? existing.previousImage : figure.previousImage,
      reason: [existing.reason, "The small or blurry exam picture is replaced by the same figure from the textbook (owner's request)."].filter(Boolean).join(" "),
      evidence: [...(existing.evidence ?? []), `main book p${figure.bookPage}: the same figure, cropped from the book page (data/book-figure-crops.json)`],
    };
  }
  return merged;
}

export const questionCorrections = withBookFigures(documentedCorrections);
